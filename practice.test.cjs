const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const core = fs.existsSync(path.join(__dirname,'dist','practice-core.js')) ? './dist/practice-core.js' : './practice-core.js';
const {ready,grade} = require(core);
const one = {options:['a','b','c','d'],correct:2};
assert.equal(grade(one,2),true);
assert.equal(grade(one,1),false);
assert.equal(ready(one,null),false);
const multi={type:'multiple',options:['a','b','c','d'],correct:[0,1,2]};
assert.equal(grade(multi,[2,0,1]),true);
assert.equal(grade(multi,[0,1]),false);
assert.equal(grade(multi,[0,1,2,3]),false);
assert.equal(grade(multi,[0,0,1,2]),false);
assert.equal(ready(multi,[]),false);
assert.equal(ready(multi,[9]),false);
const numeric={type:'numeric',answer:4.5,unit:'mL'};
assert.equal(grade(numeric,'4.50'),true);
assert.equal(grade(numeric,'4.4'),false);
for(const invalid of ['', ' ', '.', '4e0', '4,5', '4 mg', 'Infinity']) assert.equal(ready(numeric,invalid),false,invalid);
assert.equal(grade({type:'numeric',answer:0},'0'),true);
console.log('Practice grading passed: one-choice, multiple-response, and numeric answers.');
